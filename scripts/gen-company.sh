#!/usr/bin/env bash
# Writes Slips/Generated/Company.swift from `ez profile --json` (company facts are never typed by hand),
# and copies LICENSES/THIRD-PARTY.md into the app bundle's generated folder for the About screen.
#   scripts/gen-company.sh          regenerate
#   scripts/gen-company.sh --check  exit 1 when the committed files differ from what ez would write
set -euo pipefail
cd "$(dirname "$0")/.."
if command -v ez >/dev/null 2>&1; then
  EZ=(ez)
else
  EZ=(node "${ETZIAN_FOUNDATION:-$HOME/etzian/_foundation}/bin/ez.mjs")
fi
out_dir="Slips/Generated"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
"${EZ[@]}" profile --json > "$tmp/profile.json"
python3 -I - "$tmp/profile.json" "$tmp/Company.swift" <<'PY'
import json, sys
p = json.load(open(sys.argv[1], encoding="utf-8"))
def s(v): return json.dumps(v or "", ensure_ascii=False)
lines = [
    "// GENERATED by scripts/gen-company.sh from `ez profile --json` (_foundation/company/etzian.yaml).",
    "// Do not edit: change the profile, then run the script.",
    "",
    "/// Company facts shown in the app (About, Privacy). The phone number is not included: free app.",
    "enum Company {",
    f"    static let legalName = {s(p['company']['legal_name'])}",
    f"    static let brandName = {s(p['brand']['name'])}",
    f"    static let endorsementEN = {s(p['brand']['endorsement_en'])}",
    f"    static let endorsementFR = {s(p['brand']['endorsement_fr'])}",
    "    /// `{year}` is replaced with the current year.",
    f"    static let copyrightTemplate = {s(p['brand']['copyright'])}",
    f"    static let jurisdiction = {s(p['company']['jurisdiction'])}",
    f"    static let privacyOfficerName = {s(p['privacy_officer']['name'])}",
    f"    static let privacyOfficerTitleEN = {s(p['privacy_officer']['title_en'])}",
    f"    static let privacyOfficerTitleFR = {s(p['privacy_officer']['title_fr'])}",
    f"    static let privacyEmail = {s(p['contacts'].get('privacy') or p['privacy_officer']['email'])}",
    f"    static let supportEmail = {s(p['contacts'].get('support'))}",
    f"    static let domain = {s(p['brand'].get('domain'))}",
    "}",
    "",
]
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(lines))
PY
cp LICENSES/THIRD-PARTY.md "$tmp/THIRD-PARTY.md"
if [ "${1:-}" = "--check" ]; then
  diff -u "$out_dir/Company.swift" "$tmp/Company.swift" && diff -q "$out_dir/THIRD-PARTY.md" "$tmp/THIRD-PARTY.md" \
    && echo "company ok" && exit 0
  echo "Company.swift or THIRD-PARTY.md is stale: run scripts/gen-company.sh"; exit 1
fi
mkdir -p "$out_dir"
cp "$tmp/Company.swift" "$out_dir/Company.swift"
cp "$tmp/THIRD-PARTY.md" "$out_dir/THIRD-PARTY.md"
echo "wrote $out_dir/Company.swift and $out_dir/THIRD-PARTY.md"
